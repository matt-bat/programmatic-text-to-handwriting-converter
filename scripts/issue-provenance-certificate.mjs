import { createPrivateKey, createPublicKey, sign } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const [certificatePath, privateKeyPath, outputPath] = process.argv.slice(2);

if (!certificatePath || !privateKeyPath || !outputPath) {
  throw new Error('Usage: node scripts/issue-provenance-certificate.mjs <certificate.json> <private-key.pem> <output-module.js>');
}

function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  if (value && typeof value === 'object') {
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`).join(',')}}`;
  }
  return JSON.stringify(value);
}

const certificate = JSON.parse(await readFile(certificatePath, 'utf8'));
const privateKey = createPrivateKey(await readFile(privateKeyPath, 'utf8'));
const publicKey = createPublicKey(privateKey);
const signature = sign(null, Buffer.from(canonicalJson(certificate)), privateKey).toString('base64url');
const publicKeyRecord = {
  algorithm: 'Ed25519',
  keyId: publicKey.export({ format: 'der', type: 'spki' }).toString('base64url').slice(0, 24),
  spki: publicKey.export({ format: 'der', type: 'spki' }).toString('base64url'),
};
const moduleSource = `// Generated by scripts/issue-provenance-certificate.mjs. Contains no private key.\nexport const COMMERCIAL_PROVENANCE = Object.freeze(${JSON.stringify({ certificate, signature, publicKey: publicKeyRecord }, null, 2)});\n`;

await writeFile(outputPath, moduleSource, 'utf8');
